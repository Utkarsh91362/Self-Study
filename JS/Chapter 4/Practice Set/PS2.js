let sentence = "JavaScript is powerful and versatile.";


//includes
console.log(sentence.includes("versatile")) //true
console.log(sentence.includes("weak")) //false

//startswith
console.log(sentence.startsWith("Ja"))//true
console.log(sentence.startsWith("is"))//false

//endswith
console.log(sentence.endsWith("tile.")) //true
console.log(sentence.endsWith("tile")) //false  there is a dot(.) at the end of the sentence 