let day= prompt("Choose a number between 1-7")
day=Number.parseInt(day);
switch(day){
    case 1:
        alert("Sunday");
        break;
    case 2:
        alert("Monday");
        break;
    case 3:
        alert("Tuesday");
        break;
    case 4:
        alert("Wednesday");
        break;
    case 5:
        alert("Thrusday");
        break;
    case 6:
        alert("Firday");
        break;
    case 7:
        alert("Saturday");
        break;

}